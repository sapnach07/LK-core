import type { LkSettings } from '../types';
import {
  LK_BRAND_COLORS,
  LK_DENSITY_TOKENS,
  LK_FONT_FAMILY_STACK,
  LK_FONT_SCALE_PX,
} from './designTokens';
import { normalizeHex, pickAccessibleForeground } from './contrast';

export function buildPlatformTokenPayload(settings: LkSettings, resolvedMode: 'dark' | 'light') {
  const accent = normalizeHex(settings.accentColor, LK_BRAND_COLORS.gold);
  const accentForeground = pickAccessibleForeground(accent);
  const density = LK_DENSITY_TOKENS[settings.density];

  return {
    schema: 'lk.core.tokens/1.0',
    designLanguage: 'LK Hybrid Glass',
    activeMode: resolvedMode,
    colors: {
      brand: {
        obsidian: LK_BRAND_COLORS.obsidian,
        graphite: LK_BRAND_COLORS.graphite,
        gold: LK_BRAND_COLORS.gold,
        silver: LK_BRAND_COLORS.silver,
        pureWhite: LK_BRAND_COLORS.pureWhite,
      },
      semantic: {
        accent,
        accentOnColor: accentForeground,
        background: resolvedMode === 'dark' ? settings.customDarkBg : settings.customLightBg,
        surface: resolvedMode === 'dark' ? LK_BRAND_COLORS.graphite : LK_BRAND_COLORS.pureWhite,
        textPrimary: resolvedMode === 'dark' ? LK_BRAND_COLORS.pureWhite : LK_BRAND_COLORS.obsidian,
        textSecondary: resolvedMode === 'dark' ? '#C6C9D1' : '#4A4E59',
      },
    },
    glass: {
      enabled: settings.glassEnabled,
      blurPx: settings.blurIntensity,
      opacity: settings.glassOpacity,
      specularRim: settings.specularHighlight,
    },
    typography: {
      baseFontSizePx: LK_FONT_SCALE_PX[settings.fontScale],
      fontFamily: LK_FONT_FAMILY_STACK[settings.fontFamily],
    },
    density: {
      mode: settings.density,
      padding: density.pad,
      gap: density.gap,
      controlHeight: density.controlHeight,
    },
    motion: {
      level: settings.motionLevel,
      speedMultiplier: settings.motionSpeed,
      easingCurve: 'cubic-bezier(0.16, 1, 0.3, 1)',
    },
  };
}

export function exportTokensAsJson(settings: LkSettings, resolvedMode: 'dark' | 'light'): string {
  return JSON.stringify(buildPlatformTokenPayload(settings, resolvedMode), null, 2);
}

export function exportTokensAsCss(settings: LkSettings, resolvedMode: 'dark' | 'light'): string {
  const payload = buildPlatformTokenPayload(settings, resolvedMode);
  return `:root {
  --lk-accent: ${payload.colors.semantic.accent};
  --lk-accent-contrast: ${payload.colors.semantic.accentOnColor};
  --lk-bg: ${payload.colors.semantic.background};
  --lk-surface-solid: ${payload.colors.semantic.surface};
  --lk-text: ${payload.colors.semantic.textPrimary};
  --lk-text-secondary: ${payload.colors.semantic.textSecondary};
  --lk-blur: ${payload.glass.enabled ? `${payload.glass.blurPx}px` : '0px'};
  --lk-glass-opacity: ${payload.glass.opacity};
  --lk-font-size-base: ${payload.typography.baseFontSizePx}px;
  --lk-density-pad: ${payload.density.padding};
  --lk-density-gap: ${payload.density.gap};
  --lk-control-height: ${payload.density.controlHeight};
  --lk-motion-ease: ${payload.motion.easingCurve};
}`;
}

function toComposeHex(hex: string): string {
  const clean = normalizeHex(hex).slice(1);
  return `0xFF${clean}`;
}

export function exportTokensAsKotlinCompose(
  settings: LkSettings,
  resolvedMode: 'dark' | 'light',
): string {
  const payload = buildPlatformTokenPayload(settings, resolvedMode);
  return `package com.lk.core.theme

import androidx.compose.ui.graphics.Color
import androidx.compose.ui.unit.dp
import androidx.compose.ui.unit.sp

/**
 * Generated by LK Core 1.0 Design Token Exporter
 * Design Identity: LK Hybrid Glass (${resolvedMode} profile)
 */
object LkCoreTokens {
    // Brand Palette
    val Obsidian = Color(${toComposeHex(LK_BRAND_COLORS.obsidian)})
    val Graphite = Color(${toComposeHex(LK_BRAND_COLORS.graphite)})
    val LkGold = Color(${toComposeHex(LK_BRAND_COLORS.gold)})
    val Silver = Color(${toComposeHex(LK_BRAND_COLORS.silver)})
    val PureWhite = Color(${toComposeHex(LK_BRAND_COLORS.pureWhite)})

    // Active Semantic Tokens
    val Accent = Color(${toComposeHex(payload.colors.semantic.accent)})
    val OnAccent = Color(${toComposeHex(payload.colors.semantic.accentOnColor)})
    val Background = Color(${toComposeHex(payload.colors.semantic.background)})
    val Surface = Color(${toComposeHex(payload.colors.semantic.surface)})
    val TextPrimary = Color(${toComposeHex(payload.colors.semantic.textPrimary)})

    // Glass & Surface Metrics
    val GlassEnabled = ${payload.glass.enabled}
    val GlassBlurRadius = ${payload.glass.blurPx}.dp
    val GlassSurfaceAlpha = ${payload.glass.opacity}f
    val SpecularHighlight = ${payload.glass.specularRim}

    // Typography & Density
    val BaseFontSize = ${payload.typography.baseFontSizePx}.sp
    val DensityMode = "${payload.density.mode}"
    val MotionLevel = "${payload.motion.level}"
}`;
}
